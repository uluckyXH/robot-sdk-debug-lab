import re

from t1_lab._vendor.contracts.catalog import BridgeError

CATALOG = json.loads(Path(__file__).with_name("interface_catalog.json").read_text())
ENTRIES = {entry["id"]: entry for entry in CATALOG["entries"]}
DEFINITIONS = CATALOG["definitions"]
JOINTS = {joint["name"]: joint for joint in CATALOG["joints"]}
JOINT_TOPICS = {"JointCommandArray", "McCustomJointCommand"}
MOTION_INTERFACES = JOINT_TOPICS | {
    "SetServo",
    "SetMcAction",
    "SetMcMotion",
    "SetMcPresetMotion",
    "SetMcInputSource",
    "McLocomotionVelocity",
}


def entry(name):
    if name not in ENTRIES:
        raise BridgeError(404, "固定 T1 SDK 中没有这个接口")
    return ENTRIES[name]


def template(type_name):
    if type_name.endswith("[]"):
        return []
    if type_name in DEFINITIONS:
        return {field["name"]: template(field["type"]) for field in DEFINITIONS[type_name]["fields"]}
    if type_name == "string":
        return ""
    if type_name == "bool":
        return False
    return 0


