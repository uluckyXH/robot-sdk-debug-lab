def validate(type_name, value, path="payload"):
    if type_name.endswith("[]"):
        if not isinstance(value, list) or len(value) > 1048576:
            raise BridgeError(422, path + " 须为有界数组")
        return [validate(type_name[:-2], item, path + "[]") for item in value]
    if type_name in DEFINITIONS:
        fields = {field["name"]: field["type"] for field in DEFINITIONS[type_name]["fields"]}
        if not isinstance(value, dict) or set(value) - fields.keys():
            raise BridgeError(422, path + " 字段须属于 " + ", ".join(fields))
        return {key: validate(fields[key], item, path + "." + key) for key, item in value.items()}
    if type_name == "string":
        if not isinstance(value, str) or len(value) > 16384 or "\x00" in value:
            raise BridgeError(422, path + " 须为不含空字符的字符串（最多 16384 字符）")
    elif type_name == "bool":
        if type(value) is not bool:
            raise BridgeError(422, path + " 须为布尔值")
    elif type_name.startswith("float"):
        if type(value) not in (int, float) or not math.isfinite(value):
            raise BridgeError(422, path + " 须为有限数字")
        if type_name == "float32" and abs(value) > 3.4028235e38:
            raise BridgeError(422, path + " 超出 float32")
        value = float(value)
    elif match := re.fullmatch(r"(u?)int(8|16|32|64)", type_name):
        unsigned, bits = bool(match[1]), int(match[2])
        if bits == 64 and isinstance(value, str) and re.fullmatch(r"-?\d{1,20}", value):
            value = int(value)
        low, high = (0, 2**bits - 1) if unsigned else (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1)
        if type(value) is not int or not low <= value <= high:
            raise BridgeError(422, f"{path} 须为 {low}–{high} 的整数")
    else:
        raise BridgeError(422, "不支持的字段类型：" + type_name)
    return value


def payload(name, value):
    spec = entry(name)
    data = validate(spec["schema"], value)
    if name == "SetServo" and not (
        type(data.get("position")) is int
        and 0 <= data["position"] <= 90
        and type(data.get("speed")) is int
        and 100 <= data["speed"] <= 1000
    ):
        raise BridgeError(422, "舵机 position 为 0–90 度，speed 为 100–1000 步/秒")
    if name == "SetNeckLight" and data.get("brightness", 0) > 100:
        raise BridgeError(422, "brightness 范围 0–100；当前硬件仅实现开关")
    if name == "LedStripCommand" and data.get("led_strip_mode", 0) not in (*range(21), 254, 255):
        raise BridgeError(422, "灯带模式须为 0–20、254 或 255")
    if name == "SetVolume" and data.get("audio_volume", 0) > 100:
        raise BridgeError(422, "音量范围 0–100")
    if name == "PlayTts" and not data.get("tts_req", {}).get("text", "").strip():
        raise BridgeError(422, "播报文本不能为空")
    if name == "ShutdownTask" and not data.get("token", {}).get("source", "").strip():
        raise BridgeError(422, "关机请求的 token.source 不能为空")
    if name == "PlayAudioFile" and not data.get("file", {}).get("file_path", "").startswith("/"):
        raise BridgeError(422, "file.file_path 须为机器人上的绝对文件路径")
    if name == "PlayEmotion":
        if data.get("type") not in ("emotion", "file"):
            raise BridgeError(422, "type 须为 emotion（内置表情）或 file（MP4 视频）")
        if data["type"] == "emotion" and not data.get("emotion_ids"):
            raise BridgeError(422, "emotion_ids 须包含内置表情编号")
        if data["type"] == "file" and (
            not data.get("file_paths")
            or any(
                not path.startswith("/") or not path.lower().endswith(".mp4") for path in data["file_paths"]
            )
        ):
            raise BridgeError(422, "file_paths 须包含机器人上 MP4 视频的绝对路径")
    if name in JOINT_TOPICS:
        joints = data.get("joints", [])
        if not 1 <= len(joints) <= 14 or len({joint.get("name") for joint in joints}) != len(joints):
            raise BridgeError(422, "提供 1–14 个不同的正式关节名称")
        for joint in joints:
            limits = JOINTS.get(joint.get("name"))
            if limits is None or (name == "McCustomJointCommand" and not limits["upper"]):
                raise BridgeError(422, "关节不属于当前控制通道：" + str(joint.get("name")))
            if set(joint) != {"name", "position", "velocity", "effort", "stiffness", "damping"}:
                raise BridgeError(422, "关节需填写 name/position/velocity/effort/stiffness/damping")
            if (
                not limits["minimum"] <= joint["position"] <= limits["maximum"]
                or abs(joint["effort"]) > limits["max_effort"]
            ):
                raise BridgeError(422, joint["name"] + " 超出厂家位置或力矩范围")
            if joint["stiffness"] < 0 or joint["damping"] < 0:
                raise BridgeError(422, "stiffness/damping 不得为负数")
    return data


def describe():
    return {
        **CATALOG,
        "entries": [
            {**spec, "template": request_template(spec["id"]), "hardware_tested": False}
            for spec in CATALOG["entries"]
        ],
    }
